-- Live chat: website visitors and Telegram users talk to the owner through the Telegram bot.
-- Apply in Supabase SQL editor or via Supabase CLI migrations.
-- Only the service role touches these tables; visitors get replies over Realtime broadcast.

create table if not exists public.chat_sessions (
  id text primary key,
  kind text not null check (kind in ('web', 'tg')),
  name text,
  tg_chat_id bigint,
  created_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  session_id text not null references public.chat_sessions(id) on delete cascade,
  sender text not null check (sender in ('visitor', 'owner')),
  body text not null,
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_session_id_idx
  on public.chat_messages (session_id, id);

-- Maps messages in the owner's Telegram chat to the conversation they belong to,
-- so a reply can be routed back to the right person.
create table if not exists public.chat_telegram_messages (
  tg_message_id bigint primary key,
  session_id text not null references public.chat_sessions(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.chat_sessions enable row level security;
alter table public.chat_messages enable row level security;
alter table public.chat_telegram_messages enable row level security;
